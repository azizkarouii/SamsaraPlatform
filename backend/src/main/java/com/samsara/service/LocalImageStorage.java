package com.samsara.service;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.UUID;

/** Development storage: files on the local disk, served by {@link com.samsara.config.UploadsConfig}. */
@Service
@ConditionalOnProperty(name = "application.storage.type", havingValue = "local", matchIfMissing = true)
public class LocalImageStorage implements ImageStorage {

    private final Path root;

    public LocalImageStorage(@Value("${application.storage.local-dir:uploads}") String localDir) {
        this.root = Path.of(localDir).toAbsolutePath().normalize();
    }

    public Path getRoot() {
        return root;
    }

    @Override
    public String save(String folder, String extension, byte[] content) {
        String key = folder + "/" + UUID.randomUUID() + "." + extension;
        Path target = resolve(key);
        try {
            Files.createDirectories(target.getParent());
            Files.write(target, content);
        } catch (IOException e) {
            throw new UncheckedIOException("Could not store the image", e);
        }
        return key;
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException e) {
            // A leftover file is harmless; it must not make the user action fail
        }
    }

    /** Keys are generated by the server, but stay defensive against any path escaping the root. */
    private Path resolve(String key) {
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root)) {
            throw new IllegalArgumentException("Invalid image key");
        }
        return path;
    }
}
